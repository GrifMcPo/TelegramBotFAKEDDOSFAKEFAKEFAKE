# ========== /START ==========
@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    await message.delete()
    
    sent_msg = await message.answer(
        "🎉 Рады приветствовать вас в боте!\n\n"
        "Снизу находятся 3 кнопки, выберите причину использования бота:",
        reply_markup=get_main_keyboard()
    )
    
    user_data[message.from_user.id] = {
        "menu_msg_id": sent_msg.message_id,
        "username": message.from_user.username or "Нет юзернейма",
        "user_id": message.from_user.id
    }

# ========== ВЫБОР ДЕЙСТВИЯ ==========
@dp.callback_query(lambda c: c.data.startswith("action_"))
async def handle_action(callback: CallbackQuery, state: FSMContext):
    user_id = callback.from_user.id
    action = callback.data.split("_")[1]
    
    action_names = {
        "ddos": "DDos IP",
        "doks": "Doks IP",
        "probe": "Пробив IP"
    }
    
    # Удаляем меню
    menu_id = user_data.get(user_id, {}).get("menu_msg_id")
    if menu_id:
        try:
            await bot.delete_message(chat_id=user_id, message_id=menu_id)
        except:
            pass
    
    user_data[user_id]["action"] = action_names[action]
    
    await callback.message.delete()
    sent = await callback.message.answer(
        f"✅ Причина выбрана: {user_data[user_id]['action']}\n\n"
        "Введите IP снизу:"
    )
    user_data[user_id]["input_msg_id"] = sent.message_id
    
    await state.set_state(AttackStates.waiting_for_ip)
    await callback.answer()

# ========== ВВОД IP ==========
@dp.message(AttackStates.waiting_for_ip)
async def process_ip(message: types.Message, state: FSMContext):
    user_id = message.from_user.id
    ip = message.text.strip()
    
    await message.delete()
    
    # Удаляем сообщение с просьбой ввести IP
    input_id = user_data.get(user_id, {}).get("input_msg_id")
    if input_id:
        try:
            await bot.delete_message(chat_id=user_id, message_id=input_id)
        except:
            pass
    
    user_data[user_id]["ip"] = ip
    
    sent = await message.answer(
        f"🌐 IP выбрано: <code>{ip}</code>\n\n"
        "Вы готовы начать?",
        reply_markup=get_confirm_keyboard(),
        parse_mode="HTML"
    )
    user_data[user_id]["confirm_msg_id"] = sent.message_id
    
    await state.set_state(AttackStates.waiting_for_confirmation)

